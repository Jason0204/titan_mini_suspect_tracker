# Titan Mini on-panel page -- one self-contained file for SD autostart or the OpenMV IDE.
#
# Dual mode by design, one single script:
#   * standalone -- the board boots into this page. Live view, track boxes, status column and
#     detections all run on the device; no PC is required.
#   * with the host -- the PC host uploads this same text and only turns STREAM_CTRL on. The
#     firmware then pushes the CSI frame to the `stream` channel by itself, so the page keeps
#     rendering on the panel while the host receives video and the same `tracks_update` JSON
#     the headless script produces. Nothing here is host-specific.
#
# The one hard rule for that second mode: never call board.preview(False). board_preview()
# toggles FB_STREAM_ID, which is the very framebuffer the host's stream channel reads from, so
# disabling preview makes the page look fine on the panel and the host receive nothing.
#
# Changed 2026-10-18c: page rework. The old page was a 7-row grid of 8x10 text with no
# hierarchy: everything the same weight, values not aligned, and the column read as a wall of
# characters. Now there is a header strip with a live dot, one accent tick per row to carry the
# colour code, a fixed 42 px row pitch (five rows since 2026-10-18i), right-aligned numbers
# in the bottom bar, and a 2 px
# track box. Geometry lives in constants so preview_lcd_panel.py can reproduce it exactly.
#
# Changed 2026-10-18: the canvas is 400x240, not 800x480. Measured on hardware, an 800x480
# RGB565 canvas (768 KB) pushed model.predict() from 33 ms to 127 ms -- the canvas competes
# with the NPU workspace for SDRAM, and the official LCD example warns about exactly this
# ("use a half-size canvas and scale on display"). With 400x240 (187 KB) inference is back to
# ~33 ms and the frame budget fits. Do not raise this back to 800x480 to "save a scale".
#
# Panel timing comes from RASC, not from this file: 40 MHz with 1056 x 635 = 59.65 Hz.

