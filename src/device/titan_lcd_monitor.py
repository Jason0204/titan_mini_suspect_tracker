def fill(x, y, w, h, color):
    canvas.draw_rectangle((x, y, w, h), color=color, fill=True)


def label(x, y, value, color=WHITE, scale=TEXT_SCALE):
    canvas.draw_string((x, y), value, color=color, scale=scale)


def label_right(right, y, value, color=WHITE, scale=TEXT_SCALE):
    """Right-align on the fixed cell grid. mono_space is on, so the width is exact."""
    label(right - len(value) * CHAR_W * scale, y, value, color, scale)


def draw_status_background():
    """Paint the column once: header strip plus the rows' canvas.

    Rows repaint themselves on change, so the column has to start from a known colour or the
    gaps between rows keep whatever the boot screen left there.
    """
    fill(BAR_X, 0, BAR_W, CANVAS_H, PANEL_BG)
    fill(BAR_X, 0, BAR_W, HEADER_H, HEADER_BG)
    draw_text(BAR_X + BAR_PAD + 2, 0, TXT["header"], DIM, bg=HEADER_BG, ascii_top=3)
    # The dot carries the state on its own. It replaces a full STATE row that spent a line of
    # text on something a single pixel already answers.
    fill(BAR_X + BAR_W - 11, 5, 6, 6, GREEN)


def bar_row(index, name, value, color=WHITE):
    """Draw one status row, skipping the work when nothing changed.

    The status column is never touched by the video blit, so its pixels survive between
    presents; redrawing only on change keeps the steady-state cost near zero. The row is
    repainted as a whole so a shorter value cannot leave old glyphs behind. The label is a
    16 px Chinese patch (blitted), the value may be ASCII or Chinese.
    """
    key = (name, value, color)
    if _bar_cache.get(index) == key:
        return
    _bar_cache[index] = key
    y = ROW_TOP + index * ROW_STEP
    fill(BAR_X + 1, y - 3, BAR_W - 2, ROW_STEP - 6, PANEL_BG)
    fill(BAR_X + BAR_PAD, y + 1, 2, CN_GLYPH, color)
    draw_text(BAR_X + BAR_PAD + 5, 0, name, DIM, cn_top=y - 2, ascii_top=y + 2)
    draw_text(BAR_X + BAR_PAD + 5, 0, value, color, cn_top=y + 15, ascii_top=y + 15)


def draw_video_bars(frame_no, uptime):
    """Top and bottom strips. Left text is left-aligned, right text is right-aligned, so the
    two strips line up with the panel edges instead of drifting with the string length.
    Strips are 16 px tall so the 16 px Chinese patch for LIVE fits without scaling."""
    fill(0, 0, VIDEO_W, CN_GLYPH, BARS)
    label(5, 3, "TITAN MINI", WHITE)
    if is_cn_text(TXT["live"]):
        canvas.draw_image(cn_label(TXT["live"], GREEN, BARS), VIDEO_W - 5 - cn_label_w(TXT["live"]), 0)
    else:
        label_right(VIDEO_W - 5, 3, TXT["live"], GREEN)

    top = VIDEO_H - CN_GLYPH
    fill(0, top, VIDEO_W, CN_GLYPH, BARS)
    label(5, top + 3, "F%06d" % frame_no, WHITE)
    label_right(VIDEO_W - 5, top + 3, uptime, DIM)


def draw_boxes(tracked, frame_scale):
    # Boxes are reported in frame pixels; frame_scale is 1.0 at QVGA and 0.5 if a VGA frame
    # ever arrives, so the same arithmetic keeps them aligned in both cases.
    for track in tracked:
        x1, y1, x2, y2, score = track["bbox"]
        x1 = int(x1 * frame_scale)
        y1 = int(y1 * frame_scale)
        x2 = int(x2 * frame_scale)
        y2 = int(y2 * frame_scale)
        canvas.draw_rectangle((x1, y1, x2 - x1, y2 - y1), color=RED, thickness=2)

        tag = "%d %.2f" % (track["id"], score)
        tag_w = len(tag) * CHAR_W + 6
        tag_x = x1 if x1 + tag_w < VIDEO_W else VIDEO_W - tag_w
        tag_y = y1 - CHAR_H - 3
        if tag_y < HEADER_H:
            tag_y = y1 + 2
        fill(tag_x, tag_y, tag_w, CHAR_H + 2, RED)
        label(tag_x + 3, tag_y + 1, tag, WHITE)


def fmt_uptime(ms):
    total = ms // 1000
    return "%02d:%02d:%02d" % (total // 3600, (total // 60) % 60, total % 60)


# Changed 2026-10-18i: GLCDC underflow is a hardware-health datum, not operator information.
# It never goes on the panel any more. What the page does instead:
#   * samples the firmware counter (when it exists) and summarises one event per window,
#     which the host appends to hardware.log -- that log is the investigation record;
#   * eases off on its own when the panel is being starved: inference is the only consumer
#     that hogs SDRAM/总线 bandwidth, so the page stretches the detection interval for a
#     while and restores it afterwards. No user action involved.
# The counter is not exported to Python yet (titan_lcd.c only samples L1UNDF once per frame
# in line-detect); this probe makes the logic live the moment lcd.underflow_count appears.
UNDERFLOW_WINDOW_MS = 10000      # one summary line per 10 s at most -- SD/bus friendly
UNDERFLOW_RELIEF_COUNT = 20      # underflows inside a window that mean "starved"
RELIEF_FRAMES = 300              # how long the lighter cadence stays on (~22 s)
DETECT_EVERY_RELIEF = 3          # inference every 3rd frame while easing off

_underflow_probe = getattr(lcd, "underflow_count", None)
# Changed 2026-10-18i: module-level state instead of a class -- this script is uploaded as
# text through a 4 KB-payload channel and stays deliberately simple.
_underflow = {"last": None, "window_start": 0, "relief_until": 0}


def underflow_watch(now_ms, fps, infer_ms, present_ms):
    """Summarise underflow into the event log; return True while the page should ease off.

    `--` used to sit in the status column and told the operator nothing. A log line with
    fps/infer/present next to the count is what actually helps an investigation, and the
    relief branch is the countermeasure the page can take on its own.
    """
    if _underflow_probe is None:
        return False
    try:
        count = _underflow_probe()
    except Exception:
        return False
    if _underflow["last"] is None:
        _underflow["last"] = count
        _underflow["window_start"] = now_ms
        return False
    if time.ticks_diff(now_ms, _underflow["window_start"]) < UNDERFLOW_WINDOW_MS:
        return now_ms < _underflow["relief_until"]
    delta = count - _underflow["last"]
    _underflow["last"] = count
    _underflow["window_start"] = now_ms
    if delta > 0:
        print(ujson.dumps({
            "kind": "event",
            "name": "underflow",
            "payload": {
                "total": count, "delta": delta, "fps": round(fps, 1),
                "infer_ms": round(infer_ms, 1), "present_ms": round(present_ms, 1),
            },
        }))
        if delta >= UNDERFLOW_RELIEF_COUNT:
            _underflow["relief_until"] = now_ms + RELIEF_FRAMES * FRAME_PERIOD_MS
            print(ujson.dumps({
                "kind": "event",
                "name": "underflow_relief",
                "payload": {"delta": delta, "detect_every": DETECT_EVERY_RELIEF,
                            "frames": RELIEF_FRAMES},
            }))
    return now_ms < _underflow["relief_until"]


# --- track-keeper block (host-testable) ---------------------------------------
# Copied from openmv_ae3_raw_jpeg.py. Keep the two in sync: the host suspect keeper assumes
# the same id cadence from either script.
IOU_MATCH_THRESHOLD = 0.25
MAX_MISSES = 8
_next_track_id = 1
_active_tracks = []


def _iou(first, second):
    intersection_width = min(first[2], second[2]) - max(first[0], second[0])
    intersection_height = min(first[3], second[3]) - max(first[1], second[1])
    if intersection_width <= 0 or intersection_height <= 0:
        return 0.0
    intersection = intersection_width * intersection_height
    area_first = (first[2] - first[0]) * (first[3] - first[1])
    area_second = (second[2] - second[0]) * (second[3] - second[1])
    return intersection / (area_first + area_second - intersection)


def _remember_motion(track, detection):
    old = track["bbox"]
    side = 0.5 * ((old[2] - old[0]) + (old[3] - old[1]))
    dx = 0.5 * (detection[0] + detection[2] - old[0] - old[2])
    dy = 0.5 * (detection[1] + detection[3] - old[1] - old[3])
    if dx * dx + dy * dy > (1.2 * side) * (1.2 * side):
        track["vx"] = 0.0
        track["vy"] = 0.0
    else:
        track["vx"] = 0.5 * track["vx"] + 0.5 * dx
        track["vy"] = 0.5 * track["vy"] + 0.5 * dy


def _match_score(track, detection):
    x1, y1, x2, y2, _ = track["bbox"]
    vx = track["vx"]
    vy = track["vy"]
    predicted = (x1 + vx, y1 + vy, x2 + vx, y2 + vy)
    overlap = _iou(predicted, detection)
    centre_x = 0.5 * (predicted[0] + predicted[2])
    centre_y = 0.5 * (predicted[1] + predicted[3])
    dx = 0.5 * (detection[0] + detection[2]) - centre_x
    dy = 0.5 * (detection[1] + detection[3]) - centre_y
    side = 0.5 * ((predicted[2] - predicted[0]) + (predicted[3] - predicted[1]))
    distance_squared = dx * dx + dy * dy
    reach = 0.9 * side
    if distance_squared > reach * reach:
        return overlap
    fallback = IOU_MATCH_THRESHOLD + 0.25 * (1.0 - (distance_squared ** 0.5) / reach)
    return overlap if overlap > fallback else fallback


def _update_tracks(detections):
    global _next_track_id, _active_tracks
    for track in _active_tracks:
        track["misses"] += 1
    unmatched = list(range(len(detections)))
    for track in _active_tracks:
        best_index = -1
        best_score = IOU_MATCH_THRESHOLD
        for index in unmatched:
            score = _match_score(track, detections[index])
            if score > best_score:
                best_score = score
                best_index = index
        if best_index >= 0:
            _remember_motion(track, detections[best_index])
            track["bbox"] = detections[best_index]
            track["misses"] = 0
            unmatched.remove(best_index)
    for index in unmatched:
        _active_tracks.append({
            "id": _next_track_id,
            "bbox": detections[index],
            "vx": 0.0,
            "vy": 0.0,
            "misses": 0,
        })
        _next_track_id += 1
    _active_tracks = [track for track in _active_tracks if track["misses"] <= MAX_MISSES]
    return _active_tracks
# --- end track-keeper block ----------------------------------------------------


def detect(model, frame):
    detections = []
    results = model.predict([frame])
    if results:
        for entry in results[PERSON_CLASS]:
            x, y, width, height = entry[0]
            x2 = min(frame.width() - 1, int(x + width))
            y2 = min(frame.height() - 1, int(y + height))
            x1 = max(0, int(x))
            y1 = max(0, int(y))
            if x2 <= x1 or y2 <= y1:
                continue
            detections.append((x1, y1, x2, y2, float(entry[1])))
    return detections


def boot_screen(message):
    fill(0, 0, CANVAS_W, CANVAS_H, PANEL_BG)
    label((CANVAS_W - 10 * CHAR_W * 2) // 2, 92, "TITAN MINI", WHITE, 2)
    fill(CANVAS_W // 2 - 40, 122, 80, 2, RED)
    if is_cn_text(message):
        patch = cn_label(message, DIM, PANEL_BG)
        canvas.draw_image(patch, (CANVAS_W - cn_label_w(message)) // 2, 132)
    else:
        label((CANVAS_W - len(message) * CHAR_W) // 2, 134, message, DIM)
    label((CANVAS_W - len(BUILD_TAG) * CHAR_W) // 2, 150, BUILD_TAG, GRAY)
    lcd.display(canvas, x_scale=PANEL_SCALE, y_scale=PANEL_SCALE)


def force_clean_slate():
    """Changed 2026-10-18f: start from a known state, whatever the last script left behind.

    A page that is stopped while it is still tearing down (or one whose cleanup was aborted by
    the next upload) can hand over an open panel and a running CSI pipeline. Both are closed
    here so this page always initialises the hardware itself instead of inheriting it.
    """
    try:
        lcd.deinit()
    except BaseException:
        pass
    try:
        csi.CSI().shutdown(True)
    except BaseException:
        pass


def start_camera():
    """Bring the camera up, retrying instead of letting the page die.

    A page that raises during init leaves the panel on the boot screen, and the host's
    no-frame watchdog then re-uploads it every few seconds -- on the panel that looks like
    flashing. Three attempts with a short pause cost nothing when they are not needed.
    """
    last_error = None
    for attempt in range(3):
        try:
            cam = csi.CSI()
            cam.reset()
            cam.pixformat(csi.RGB565)
            cam.framesize(csi.QVGA)
            # Changed 2026-10-18f: three delayed snapshots instead of one long one. Coming from
            # an unclean handover the sensor starts from an odd AE/AWB state, and a single
            # 2 s snapshot let the first seconds of the page visibly breathe.
            for _ in range(3):
                cam.snapshot(time=800)
            return cam
        except BaseException as exc:  # noqa: BLE001 - never let init kill the page
            last_error = exc
            print(ujson.dumps({
                "kind": "event",
                "name": "page_init_retry",
                "payload": {"page": "lcd", "attempt": attempt + 1, "error": repr(exc)},
            }))
            time.sleep_ms(400)
    raise last_error


